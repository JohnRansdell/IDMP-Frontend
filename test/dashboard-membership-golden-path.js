import assert from 'node:assert/strict'
export async function runMembershipGoldenPath(cdp, { click, domClick, value, waitFor, delay, reload }) {
  await click(cdp, '[data-testid="dashboard-edit"]')
  await waitFor(cdp, `document.querySelector('[data-testid="dashboard-canvas"]')`)
  const diagnostic = () => value(cdp, `(() => { const el = document.querySelector('[data-testid="dashboard-canvas"]'); return el.__vueParentComponent.exposed.getMembershipDiagnostic(); })()`)
  const savedCount = count => waitFor(cdp, `JSON.parse(localStorage.getItem('idmp:dashboard-schema:v1:quality-overview')).widgets.length === ${count} && document.querySelector('.dashboard-save-state')?.textContent.includes('已保存')`)
  const resetViaMenu = async () => {
    await value(cdp, `document.querySelector('.studio-command-actions .el-dropdown').dispatchEvent(new MouseEvent('mouseenter', { bubbles: true }))`)
    await waitFor(cdp, `[...document.querySelectorAll('.el-dropdown-menu__item')].some(item => item.textContent.includes('恢复默认布局'))`)
    await value(cdp, `[...document.querySelectorAll('.el-dropdown-menu__item')].find(item => item.textContent.includes('恢复默认布局')).click()`)
  }
  await domClick(cdp, '[data-testid="dashboard-add-widget"]')
  await delay(100)
  // The existing More menu is hover-triggered; opening it is still a UI gesture.
  await value(cdp, `document.querySelector('.studio-command-actions .el-dropdown').dispatchEvent(new MouseEvent('mouseenter', { bubbles: true }))`)
  await delay(400)
  await value(cdp, `[...document.querySelectorAll('.el-dropdown-menu__item')].find(item => item.textContent.includes('恢复默认布局')).click()`)
  await delay(150)
  await domClick(cdp, '[data-testid="dashboard-save"]')
  const reset = await diagnostic()
  process.stdout.write('membership-reset-diagnostic: ' + JSON.stringify(reset) + '\n')
  assert.equal(reset.valid, true, 'reset must remove nodes absent from canonical schema')
  await savedCount(6)
  const defaultIds = new Set(reset.schemaIds)
  // Both click handlers execute in ONE browser task. No sleep/nextTick between add and save.
  await value(cdp, `document.querySelector('[data-testid="dashboard-add-widget"]').click(); document.querySelector('[data-testid="dashboard-save"]').click()`)
  await savedCount(7)
  const added = await diagnostic()
  assert.equal(added.valid, true)
  const addedId = added.schemaIds.find(id => !defaultIds.has(id))
  await click(cdp, `[data-widget-id="${addedId}"]`)
  await value(cdp, `document.querySelector('[data-testid="dashboard-delete-widget"]').click(); document.querySelector('[data-testid="dashboard-save"]').click()`)
  await savedCount(6)
  assert.equal((await diagnostic()).valid, true)
  await click(cdp, '[data-testid="dashboard-library-line"]')
  await domClick(cdp, '[data-testid="dashboard-add-widget"]')
  await click(cdp, '[data-testid="dashboard-configure-widget"]')
  await click(cdp, '[data-testid="binding-slot-dimensions"]')
  await click(cdp, '[data-testid="binding-field-month"]')
  await waitFor(cdp, `document.querySelector('[data-testid="binding-invalid"]')`)
  await domClick(cdp, '[data-testid="dashboard-save"]')
  await savedCount(7)
  assert.equal((await diagnostic()).valid, true, 'invalid binding must retain DOM and engine membership')
  for (const id of (await diagnostic()).schemaIds) {
    await click(cdp, `[data-widget-id="${id}"]`)
    await domClick(cdp, '[data-testid="dashboard-delete-widget"]')
  }
  await domClick(cdp, '[data-testid="dashboard-save"]')
  await savedCount(0)
  const empty = await diagnostic()
  assert.equal(empty.valid, true); assert.deepEqual(empty.gridIds, []); assert.deepEqual(empty.dom, [])
  await reload(cdp)
  await waitFor(cdp, `document.querySelector('[data-testid="dashboard-edit"]')`)
  await click(cdp, '[data-testid="dashboard-edit"]')
  await waitFor(cdp, `document.querySelector('[data-testid="dashboard-canvas"]')`)
  assert.equal((await diagnostic()).schemaWidgetCount, 0)
  await resetViaMenu()
  await domClick(cdp, '[data-testid="dashboard-save"]')
  await savedCount(6)
  assert.equal((await diagnostic()).valid, true, 'restoring defaults after empty must re-register detached ids')
  process.stdout.write('dashboard-membership-golden-path: PASS (reset, add/immediate save, delete/save, invalid binding/save, delete last/save/reload, restore defaults)\n')
  await reload(cdp)
  await waitFor(cdp, `document.querySelector('[data-testid="dashboard-edit"]')`)
}
