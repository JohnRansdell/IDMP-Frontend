import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { mkdir, writeFile } from 'node:fs/promises'

const { chromium } = createRequire(process.env.IDMP_PLAYWRIGHT_PACKAGE || 'C:/Users/啾啾/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/package.json')('playwright')
const origin = process.env.IDMP_FRONTEND_URL || 'http://127.0.0.1:5176'
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
const checks = [], errors = []
const folder = '.tmp/search-keyboard'
await mkdir(folder, { recursive: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`${origin}/test/fixtures/search-keyboard.html`)
  const input = id => page.locator('section').filter({ has: page.locator(`#${id}`) }).locator('input').first()
  const highlighted = () => page.locator('.el-select-dropdown:visible .is-hovering')
  async function search(id, text, first) {
    const previous = id === 'remote' ? await page.locator('#remote-query').textContent() : ''
    await input(id).fill(text)
    if (id === 'remote') await page.waitForFunction(({ text, previous }) => {
      const completed = document.getElementById('remote-query')?.textContent
      return completed !== previous && completed.endsWith(`:${text}`)
    }, { text, previous })
    await page.waitForFunction(expected => {
      const items = [...document.querySelectorAll('.el-select-dropdown .is-hovering')].filter(item => item.getClientRects().length)
      return items.some(item => item.textContent.includes(expected))
    }, first)
  }
  async function selected(id, value, name) {
    await page.waitForFunction(({ id, value }) => document.getElementById(id)?.textContent === value, { id, value })
    assert.equal(await page.locator('#queries').textContent(), '0', 'candidate selection must not submit the query form')
    checks.push({ name, passed: true })
    console.log(JSON.stringify(checks.at(-1)))
  }
  await search('field', '科室', '科室编码')
  const highlightStyle = await highlighted().evaluate(item => ({ background: getComputedStyle(item).backgroundColor, marker: getComputedStyle(item).boxShadow }))
  assert.equal(highlightStyle.background, 'rgb(231, 241, 248)')
  assert.match(highlightStyle.marker, /inset/)
  await page.screenshot({ path: `${folder}/first-candidate-highlight.png` })
  await input('field').press('Enter')
  await selected('field', 'DEPT', '输入后直接回车选择首项')
  await search('field', '科室', '科室编码')
  await input('field').press('ArrowDown')
  assert.equal(await highlighted().count(), 1, 'only the current candidate is highlighted')
  assert.match(await highlighted().textContent(), /科室名称/)
  assert.equal(await highlighted().evaluate(item => getComputedStyle(item).backgroundColor), highlightStyle.background)
  await page.screenshot({ path: `${folder}/arrow-candidate-highlight.png` })
  await input('field').press('Enter')
  await selected('field', 'DEPT_NAME', '向下移动后回车选择第二项')
  await search('field', '科室', '科室编码')
  await input('field').press('ArrowDown')
  await input('field').press('ArrowUp')
  await input('field').press('Enter')
  await selected('field', 'DEPT', '向上返回首项')
  await search('field', '科室', '科室编码')
  await page.locator('.el-select-dropdown:visible .el-select-dropdown__item:visible').nth(1).hover()
  assert.equal(await highlighted().count(), 1)
  assert.match(await highlighted().textContent(), /科室名称/)
  await input('field').press('ArrowUp')
  assert.match(await highlighted().textContent(), /科室编码/)
  await input('field').press('Enter')
  await selected('field', 'DEPT', '鼠标与方向键共用唯一当前高亮项')
  await input('field').fill('没有这个字段')
  await page.locator('.el-select-dropdown:visible').getByText('No matching data', { exact: true }).waitFor()
  await input('field').press('Enter')
  await selected('field', 'DEPT', '无匹配项不修改原值也不提交')
  await input('field').press('Escape')
  await search('field', '医生', '医生编码')
  await input('field').dispatchEvent('compositionstart')
  await input('field').dispatchEvent('keydown', { key: 'Enter', code: 'Enter', isComposing: true, keyCode: 229 })
  await selected('field', 'DEPT', '中文输入法确认不选择候选项')
  await input('field').dispatchEvent('compositionend', { data: '医生' })
  await input('field').press('Escape')

  await search('multiple', '科室', '科室一')
  await input('multiple').press('Enter')
  await selected('multiple', '["1"]', '多选跳过禁用项并确认首项')
  await input('multiple').press('ArrowDown')
  await input('multiple').press('Enter')
  await selected('multiple', '["1","2"]', '多选继续用方向键选择另一项')
  await input('multiple').press('Escape')

  await search('remote', '科室', '科室一')
  await input('remote').press('Enter')
  await selected('remote', '1', '远程候选返回后默认第一项')
  await search('remote', '科室', '科室一')
  await input('remote').press('ArrowDown')
  await input('remote').press('Enter')
  await selected('remote', '2', '远程候选方向键选择')
  await search('remote', '三', '科室三')
  await input('remote').press('Enter')
  await selected('remote', '3', '重新搜索后高亮重置到新结果首项')

  await search('virtual', '科室', '科室一')
  await input('virtual').press('ArrowDown')
  await input('virtual').press('Enter')
  await selected('virtual', '2', '虚拟列表键盘选择并跳过禁用项')

  const category = input('category')
  const categoryActive = page.locator('.el-cascader__suggestion-item.is-keyboard-active')
  await category.fill('质量')
  await categoryActive.filter({ hasText: '住院质量' }).waitFor()
  assert.equal(await categoryActive.evaluate(item => getComputedStyle(item).backgroundColor), highlightStyle.background)
  await category.press('Enter')
  await selected('category', '["quality","inpatient"]', '分类搜索回车选择首项')
  await category.fill('质量')
  await categoryActive.filter({ hasText: '住院质量' }).waitFor()
  await category.press('ArrowDown')
  assert.match(await categoryActive.textContent(), /手术质量/)
  await category.press('Enter')
  await selected('category', '["quality","surgery"]', '分类搜索向下选择')
  await category.fill('质量')
  await categoryActive.filter({ hasText: '住院质量' }).waitFor()
  await category.press('ArrowDown')
  await category.press('ArrowUp')
  await category.press('Enter')
  await selected('category', '["quality","inpatient"]', '分类搜索向上选择')
  await category.fill('不存在的分类')
  await page.locator('.el-cascader__empty-text:visible').waitFor()
  await category.press('Enter')
  await selected('category', '["quality","inpatient"]', '分类无结果时不误选或提交')
  await category.press('Escape')
  for (const [index, id] of ['field', 'virtual', 'multiple', 'remote'].entries()) {
    for (let attempt = 0; attempt < 2 && await input(id).getAttribute('aria-expanded') !== 'false'; attempt++) await input(id).press('Escape')
    await input(id).press('Enter')
    await page.waitForFunction(count => document.getElementById('queries')?.textContent === String(count), index + 1)
    checks.push({ name: `${id} 选择完成并收起列表后回车查询`, passed: true })
    console.log(JSON.stringify(checks.at(-1)))
  }
  await page.screenshot({ path: `${folder}/keyboard.png` })
  assert.deepEqual(errors, [])
} finally {
  await writeFile(`${folder}/results.json`, JSON.stringify({ checks, errors }, null, 2))
  await browser.close()
}
